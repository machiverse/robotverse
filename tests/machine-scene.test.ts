import assert from "node:assert/strict";
import { groundSceneProcesses, identifySceneMachine, sceneProcessesFromSolution, sceneProcessesFromMedia } from "../src/features/automation3d/machineScene";
import { processesFromSkills } from "../src/utils/processAnalyzer";
import { engineSolution } from "../src/features/automation3d/solutionEngine";
import { planLine } from "../src/features/automation3d/robotKnowledge";

assert.equal(identifySceneMachine("Load a CNC lathe with shafts")?.family, "lathe");
assert.equal(identifySceneMachine("Load the injection moulding machine")?.family, "injection");
assert.equal(identifySceneMachine("Heller reflow oven")?.family, "reflow");
assert.equal(identifySceneMachine("an unidentified machine"), undefined);
const solution = engineSolution("Load and unload a CNC lathe with 5 kg shafts");
const station = { ...solution.stations[0], skill: "CNC Machine Tending", name: "Lathe OP10", what: "Load CNC lathe shafts", tooling: "Dual shaft gripper", payload_kg: 18, cycle_s: 40 };
const cards = sceneProcessesFromSolution({ ...solution, stations: [station, { ...station, name: "Lathe OP20" }] }, "Load two CNC lathes");
assert.equal(cards.length, 2, "Repeated machine skills remain separate operations");
assert.equal(cards[0].scene?.tooling, "Dual shaft gripper");
assert.equal(cards[0].scene?.cycleS, 40);
assert.equal(cards[0].scene?.payloadKg, 18);
const plan = planLine(cards);
assert.equal(plan.sim.cells.flatMap((c) => c.machines ?? []).length, 2);
assert.equal(plan.robots[0].steps.filter((s) => s.action === "process").length, 2);
assert.equal(new Set(plan.robots[0].steps.filter((s) => s.action === "process").map((s) => s.station)).size, 2);
assert.ok(plan.robots[0].minPayload >= 18);
const threeMachines = planLine([...cards, { ...cards[0], scene: cards[0].scene ? { ...cards[0].scene, id: "operation-3" } : undefined }]);
assert.equal(threeMachines.robots.length, 2, "Three explicit machines split before a third station becomes unreachable");
const paint = groundSceneProcesses(processesFromSkills(["Spray Painting"]), "Paint frames next to a CNC lathe");
assert.equal(paint[0]?.scene?.machine, undefined, "Incidental machines do not replace robot process tools");
const media = sceneProcessesFromMedia({ summary: "Operator loads a CNC lathe", description: "Load shafts and unload finished shafts", tasks: ["CNC Machine Tending"], manual_steps: ["Load CNC lathe"], workpiece: null, observations: [], confidence: "medium" });
assert.equal(media[0].scene?.machine?.family, "lathe");
assert.equal(media[0].scene?.machine?.origin, "analysis");
const legacy = planLine(processesFromSkills(["CNC Machine Tending"]));
assert.ok(legacy.robots[0].steps.some((s) => s.station === "cnc"));
assert.equal(legacy.sim.cells[0].machines?.length, 0);
console.log("Machine-grounded scene rules passed");